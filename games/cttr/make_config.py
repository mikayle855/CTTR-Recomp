#!/usr/bin/env python3
"""Merge the Ghidra export and the ps2_analyzer output into the committed CTTR build inputs.

    python games/cttr/make_config.py <ghidra.toml> <ghidra.csv> <analyzer.toml>

CTTR's ELF is stripped, so Ghidra only names the kernel syscall wrappers. ps2_analyzer's SCE
symbol database recognises the SDK libraries (sceCd*, scePad*, sceMc*, sceSif*, sceGs*, ...)
by code hash. This keeps Ghidra's function boundaries and:
  - stubs  = Ghidra's stubs + the analyzer's (the runtime replaces these with host versions);
  - names  = SDK names written into the CSV for every recognised function, so logs are readable;
  - [mmio] = the analyzer's MMIO address table.
Writes games/cttr/config.toml.in and games/cttr/functions.csv.
"""
import csv
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
# Recognised SDK functions with no runtime handler of their own, bound to one with the same calling convention.
# kprintf: the real one busy-waits on the EE SIO port, which nothing drains -- the main thread spent 78% there.
# isceSifSendCmd: the interrupt-context twin the game calls from inside its SIF handler; it must reach the same
# host handler (CTTR's IOP driver HLE answers there) instead of running the real code against SIF registers.
STUB_ALIASES = {"kprintf": "scePrintf", "isceSifSendCmd": "sceSifSendCmd"}
# Recognised library functions that must run as the game's own code, not as a runtime replacement: pure memory /
# maths code with nothing to emulate. Packet builders above all -- the game mixes them with unreplaced siblings
# (sceVif1PkCnt) on one sceVif1Packet, and the host versions kept their own state, so the DMA tags came out with
# stale sizes and the frame-end packet carrying GS FINISH never parsed. Maths and libc run exactly as on the PS2.
STUB_EXCLUDE = {
    "sceGifPkCloseGifTag", "sceGifPkAddGsAD", "sceVif1PkOpenDirectCode", "sceVif1PkCloseGifTag", "sceVif1PkAddGsAD",
    "memclr", "memcmp", "strrchr", "rand", "exp", "pow", "fabs", "__ieee754_rem_pio2f", "__divdi3",
}


def toml_list(text: str, key: str) -> list:
    m = re.search(rf'^{key}\s*=\s*\[(.*?)^\]', text, re.S | re.M)
    return re.findall(r'"([^"]+)"', m.group(1)) if m else []


def by_addr(selectors: list) -> dict:
    return {int(s.rsplit("@", 1)[1], 16): s.rsplit("@", 1)[0] for s in selectors}


def main() -> None:
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    ghidra_toml, ghidra_csv, analyzer_toml = (Path(a).read_text() for a in sys.argv[1:4])
    ghidra_csv_path = Path(sys.argv[2])

    stubs = by_addr(toml_list(ghidra_toml, "stubs"))
    stubs.update(by_addr(toml_list(analyzer_toml, "stubs")))
    names = by_addr(toml_list(analyzer_toml, "untracked_stubs"))
    names.update(stubs)
    for addr, name in names.items():
        if name in STUB_ALIASES and addr not in stubs:
            stubs[addr] = STUB_ALIASES[name]
    stubs = {a: n for a, n in stubs.items() if n not in STUB_EXCLUDE}

    rows = list(csv.DictReader(ghidra_csv_path.open(newline="")))
    # Ghidra leaves a stray 1-byte "function" in .rodata (0x5338b8): nothing shorter than one instruction is code.
    dropped = [r["Name"] for r in rows if int(r["Size"]) < 4]
    rows = [r for r in rows if int(r["Size"]) >= 4]
    renamed = 0
    for r in rows:
        name = names.get(int(r["Start"], 16))
        if name in STUB_EXCLUDE:
            name = "native_" + name   # the recompiler also stubs any function whose NAME has a runtime handler
        if name and r["Name"] != name:
            r["Name"] = name
            renamed += 1
    with (HERE / "functions.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["Name", "Start", "End", "Size"], lineterminator="\n")
        w.writeheader()
        w.writerows(rows)

    starts = {int(r["Start"], 16) for r in rows}
    unbound = [f"{n}@0x{a:08X}" for a, n in sorted(stubs.items()) if a not in starts]
    stub_lines = "".join(f'  "{n}@0x{a:08X}",\n' for a, n in sorted(stubs.items()) if a in starts)
    mmio = re.search(r'^\[mmio\]\n(.*?)(?=^\[|\Z)', analyzer_toml, re.S | re.M)

    (HERE / "config.toml.in").write_text(
        "# PS2Recomp configuration for Crash Tag Team Racing (SLES_534.39).\n"
        "# Generated by games/cttr/make_config.py from the Ghidra export + ps2_analyzer; setup.py fills in the paths.\n\n"
        "[general]\n"
        'input = "@ELF@"\n'
        'ghidra_output = "@CSV@"\n'
        'output = "@OUT@"\n'
        "single_file_output = false\n"
        "patch_syscalls = false\n"
        "patch_cop0 = true\n"
        "patch_cache = true\n"
        f"stubs = [\n{stub_lines}]\n"
        "skip = []\n"
        + (f"\n[mmio]\n{mmio.group(1).rstrip()}\n" if mmio else ""))

    print(f"functions.csv: {len(rows)} functions, {renamed} renamed to SDK names"
          + (f", dropped {', '.join(dropped)}" if dropped else ""))
    print(f"config.toml.in: {len(stubs) - len(unbound)} stubs bound")
    if unbound:
        print(f"  not function starts in the Ghidra map (left out): {', '.join(unbound)}")


if __name__ == "__main__":
    main()
